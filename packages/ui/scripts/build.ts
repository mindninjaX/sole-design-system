// Writes packages/ui/dist: the four files consumers import (styles.css, tokens.css,
// tokens.json) and the JavaScript entry (index.js with its types). Run with
// `npm run build -w @soleapp/ui`, which builds the tokens first.
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokens } from '../../tokens/src/tokens.ts';
import type { Token, TokenTree } from '../../tokens/src/tokens.ts';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = resolve(packageRoot, 'dist');

function isToken(node: Token | TokenTree): node is Token {
  return '$value' in node;
}

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** The type of the token tree: every group and leaf by name, so `tokens.color.primary` is checked. */
function renderType(tree: TokenTree, indent: string): string {
  const inner = `${indent}  `;
  const rows = Object.entries(tree).map(([name, node]) => {
    const key = IDENTIFIER.test(name) ? name : JSON.stringify(name);
    return `${inner}readonly ${key}: ${isToken(node) ? 'Token' : renderType(node, inner)};`;
  });
  return `{\n${rows.join('\n')}\n${indent}}`;
}

const types = `/* Generated by packages/ui/scripts/build.ts. Do not edit. */

export type TokenType = 'color' | 'dimension' | 'fontFamily' | 'shadow' | 'cubicBezier' | 'number';

/** One design token in the DTCG shape. */
export interface Token {
  readonly $value: string;
  readonly $type: TokenType;
  readonly $description?: string;
}

/** Sole's design tokens, the same tree as tokens.json. */
export declare const tokens: ${renderType(tokens, '')};
`;

const js = `// Generated by packages/ui/scripts/build.ts. Do not edit.
export const tokens = ${JSON.stringify(tokens, null, 2)};
`;

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

// The tokens build wrote these two; they must exist, or the package would ship without them.
const tokensCss = resolve(packageRoot, 'src/styles/tokens.css');
const tokensJson = resolve(packageRoot, '../tokens/dist/tokens.json');
for (const path of [tokensCss, tokensJson]) readFileSync(path);

copyFileSync(resolve(packageRoot, 'src/styles/styles.css'), resolve(dist, 'styles.css'));
copyFileSync(tokensCss, resolve(dist, 'tokens.css'));
copyFileSync(tokensJson, resolve(dist, 'tokens.json'));
writeFileSync(resolve(dist, 'index.js'), js);
writeFileSync(resolve(dist, 'index.d.ts'), types);
