// Builds packages/ui/dist: the compiled parts (tsc, no bundler), the stylesheet files and
// the token JSON. Run with `npm run build -w @sole-ui/react`, which builds the tokens first.
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokens } from '../../tokens/src/tokens.ts';
import type { Token, TokenTree } from '../../tokens/src/tokens.ts';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = resolve(packageRoot, 'dist');

function isToken(node: Token | TokenTree): node is Token {
  return '$value' in node;
}

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** The type of the token tree: every group and leaf by name, so `tokens.color.primary` is checked. */
function renderType(tree: TokenTree, indent: string): string {
  const inner = `${indent}  `;
  const rows = Object.entries(tree).map(([name, node]) => {
    const key = IDENTIFIER.test(name) ? name : JSON.stringify(name);
    return `${inner}readonly ${key}: ${isToken(node) ? 'Token' : renderType(node, inner)};`;
  });
  return `{\n${rows.join('\n')}\n${indent}}`;
}

// The tokens as a typed module, so tsc compiles them with the parts. Committed, like tokens.css.
const generated = `// Generated by packages/ui/scripts/build.ts. Do not edit.

export type TokenType = 'color' | 'dimension' | 'fontFamily' | 'shadow' | 'cubicBezier' | 'number';

/** One design token in the DTCG shape. */
export interface Token {
  readonly $value: string;
  readonly $type: TokenType;
  readonly $description?: string;
}

/** Sole's design tokens, the same tree as tokens.json. */
export const tokens: ${renderType(tokens, '')} = ${JSON.stringify(tokens, null, 2)};
`;
writeFileSync(resolve(packageRoot, 'src/tokens.generated.ts'), generated);

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

// The tokens build wrote these two; they must exist, or the package would ship without them.
const tokensCss = resolve(packageRoot, 'src/styles/tokens.css');
const tokensJson = resolve(packageRoot, '../tokens/dist/tokens.json');
for (const path of [tokensCss, tokensJson]) readFileSync(path);

// The compiler comes from the workspace's node_modules, with the node that runs this script.
execFileSync(process.execPath, [resolve(packageRoot, '../../node_modules/typescript/bin/tsc'), '-p', 'tsconfig.build.json'], {
  cwd: packageRoot,
  stdio: 'inherit',
});

// styles.css points Tailwind at the parts' source. The source copy sits in src/styles, so it
// says "../" (src); the copy in dist sits next to the compiled parts, so it says "./" (dist).
const styles = readFileSync(resolve(packageRoot, 'src/styles/styles.css'), 'utf8');
if (!styles.includes('@source "../";')) throw new Error('Could not find the @source line in styles.css.');
writeFileSync(resolve(dist, 'styles.css'), styles.replace('@source "../";', '@source "./";'));
copyFileSync(tokensCss, resolve(dist, 'tokens.css'));
copyFileSync(tokensJson, resolve(dist, 'tokens.json'));
